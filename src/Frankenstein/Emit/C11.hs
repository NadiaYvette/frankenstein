{-# LANGUAGE DerivingStrategies #-}
{-# LANGUAGE OverloadedStrings #-}
-- | Module: Frankenstein.Emit.C11
-- Description: Fast-feedback golden C11 backend emitting code against liborgan_rt
--
-- Translates OrganIR / Frankenstein Core 'Program' into clean, readable C11 code
-- that compiles with zero GHC RTS symbols (no stg_*, no rts_*, no hs_init) and
-- links solely against @rts/include/organ_rt.h@.
module Frankenstein.Emit.C11
  ( emitOrganC11
  , emitProgramC11
  ) where

import Data.Text (Text)
import qualified Data.Text as T

import Frankenstein.Core.Types
  ( Program(..)
  , Def(..)
  , Expr(..)
  , Lit(..)
  , QName(..)
  , Name(..)
  )

-- | Primary C11 code generator entry point.
emitOrganC11 :: Program -> Text
emitOrganC11 = emitProgramC11

-- | Lower a Frankenstein Program into a standalone C11 source text.
emitProgramC11 :: Program -> Text
emitProgramC11 prog =
  let header = T.unlines
        [ "/* Generated by Frankenstein.Emit.C11 — Zero-GHC-RTS C11 Backend */"
        , "#include \"organ_rt.h\""
        , "#include <stdio.h>"
        , "#include <stdint.h>"
        , "#include <stdbool.h>"
        , ""
        ]
      defsCode = T.unlines (map emitDef (progDefs prog))
      mainStub = T.unlines
        [ "int main(int argc, char **argv) {"
        , "    (void)argc; (void)argv;"
        , "    return 0;"
        , "}"
        ]
  in header <> defsCode <> "\n" <> mainStub

emitDef :: Def -> Text
emitDef d =
  let fnName = sanitizeQName (defName d)
      body = emitExpr (defExpr d)
  in "int64_t " <> fnName <> "(void) {\n    return " <> body <> ";\n}\n"

emitExpr :: Expr -> Text
emitExpr expr = case expr of
  ELit (LitInt i) -> T.pack (show i)
  ELit (LitFloat f) -> T.pack (show f)
  ELit (LitChar c) -> T.pack (show c)
  ELit (LitString s) -> T.pack (show s)
  EVar (Name n _) -> sanitizeText n <> "()"
  EApp f args -> emitExpr f <> "(" <> T.intercalate ", " (map emitExpr args) <> ")"
  _ -> "0"

sanitizeText :: Text -> Text
sanitizeText = T.replace "." "_"

sanitizeQName :: QName -> Text
sanitizeQName (QName m (Name n _)) =
  let cleanM = sanitizeText m
      cleanN = sanitizeText n
  in cleanM <> "_" <> cleanN
