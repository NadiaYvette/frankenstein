-- | Supported Track 3 idiomatic and outbound FFI emission targets.
data TranspileTarget
  = TargetRust
  | TargetC11
  | TargetRocq
  | TargetPythonExt
  | TargetFortranFfi
  deriving stock (Eq, Ord, Show, Enum, Bounded)

-- | Idiomatic Rust ownership strategy derived directly from 'MemProfile'.
data OwnershipRustType
  = RustOwnedMove
  | RustRcReuse
  | RustArcShared
  deriving stock (Eq, Ord, Show)

-- | Maps OrganIR 3-profile Perceus semantics onto idiomatic Rust ownership.
mapProfileToRustOwnership :: MemProfile -> OwnershipRustType
mapProfileToRustOwnership Profile0FreestandingLinear = RustOwnedMove
mapProfileToRustOwnership Profile1ThreadLocalPerceus = RustRcReuse
mapProfileToRustOwnership Profile2ConcurrentShared   = RustArcShared

-- | Canonical C/ABI symbol sanitization matching 'Frankenstein.Linker.PolyglotLink'.
sanitizeAbiSymbol :: Text -> Text
sanitizeAbiSymbol = T.map (\c -> if c == '.' || c == ':' || c == '-' then '_' else c)

-- | Emits a readable, borrow-checker-clean Rust module shaped by 'StyleProfile'.
emitIdiomaticRustModule :: StyleProfile -> OrganInterface -> Text
emitIdiomaticRustModule sp iface =
  let ind       = T.replicate (spIndentWidth sp) " "
      needsRc   = any ((== Profile1ThreadLocalPerceus) . eaProfile) (oiExports iface)
      needsArc  = any ((== Profile2ConcurrentShared) . eaProfile) (oiExports iface)
      imports   = [ "use std::rc::Rc;" | needsRc ]
                  ++ [ "use std::sync::Arc;" | needsArc ]
      tagConsts = map renderTagConst (oiCtors iface)
      fnStubs   = map (renderRustFn ind) (oiExports iface)
  in T.unlines $
       [ "// Generated by Ingolstadt (Frankenstein.Emit.Idiomatic) — ownership-preserving Rust"
       , "// Source module: " <> oiModuleName iface <> " (" <> oiSourceLang iface <> ")"
       ]
       ++ imports
       ++ ["" | not (null imports)]
       ++ tagConsts
       ++ ["" | not (null tagConsts)]
       ++ fnStubs
  where
    renderTagConst cd =
      let constName = T.toUpper (formatIdentifier SnakeCase (cdQualifiedName cd)) <> "_TAG"
      in "pub const " <> constName <> ": u64 = " <> T.pack (show (unContentTag (cdTag cd))) <> ";"

    renderRustFn ind ex =
      let fnName   = formatIdentifier (spValueNaming sp) (eaQualifiedName ex)
          totalArg = eaArity ex + eaEvParams ex
          params   = T.intercalate ", " ["a" <> T.pack (show i) <> ": i64" | i <- [0 .. totalArg - 1]]
          ownDoc   = case mapProfileToRustOwnership (eaProfile ex) of
                       RustOwnedMove -> "/// OrganIR Profile 0 (#[freestanding_linear]): zero RC, move/in-place semantics."
                       RustRcReuse   -> "/// OrganIR Profile 1 (#[thread_local_perceus]): Rc<T> + Rc::make_mut reuse."
                       RustArcShared -> "/// OrganIR Profile 2 (#[concurrent_shared]): Arc<T> atomic sharing."
          retExpr  = if totalArg > 0 then "a0" else "0"
      in T.unlines
           [ ownDoc
           , "pub fn " <> fnName <> "(" <> params <> ") -> i64 {"
           , ind <> retExpr
           , "}"
           ]

-- | Emits a zero-GC CPython C-API native extension wrapping every exported ABI symbol.
emitPythonCapiExtension :: OrganInterface -> Text
emitPythonCapiExtension iface =
  let modSym    = T.toLower (sanitizeAbiSymbol (oiModuleName iface))
      externs   = map renderExtern (oiExports iface)
      wrappers  = map renderPyWrapper (oiExports iface)
      methodTbl = map renderMethodRow (oiExports iface)
  in T.unlines $
       [ "/* Generated by Frankenstein.Emit.Idiomatic — CPython C-API Native Extension */"
       , "#define PY_SSIZE_T_CLEAN"
       , "#include <Python.h>"
       , "#include <stdint.h>"
       , ""
       ]
       ++ externs
       ++ [""]
       ++ wrappers
       ++ [ "static PyMethodDef " <> modSym <> "_methods[] = {" ]
       ++ methodTbl
       ++ [ "    {NULL, NULL, 0, NULL}"
          , "};"
          , ""
          , "static struct PyModuleDef " <> modSym <> "_module = {"
          , "    PyModuleDef_HEAD_INIT, \"" <> modSym <> "\", NULL, -1, " <> modSym <> "_methods"
          , "};"
          , ""
          , "PyMODINIT_FUNC PyInit_" <> modSym <> "(void) {"
          , "    return PyModule_Create(&" <> modSym <> "_module);"
          , "}"
          ]
  where
    renderExtern ex =
      let n = eaArity ex + eaEvParams ex
          ps = if n <= 0 then "void" else T.intercalate ", " (replicate n "int64_t")
      in "extern int64_t " <> sanitizeAbiSymbol (eaQualifiedName ex) <> "(" <> ps <> ");"

    renderPyWrapper ex =
      let cSym   = sanitizeAbiSymbol (eaQualifiedName ex)
          n      = eaArity ex + eaEvParams ex
          decls  = ["    long long a" <> T.pack (show i) <> " = 0;" | i <- [0 .. n - 1]]
          fmtStr = T.replicate n "L"
          refs   = T.intercalate ", " ["&a" <> T.pack (show i) | i <- [0 .. n - 1]]
          callPs = T.intercalate ", " ["(int64_t)a" <> T.pack (show i) | i <- [0 .. n - 1]]
          parseLine =
            if n <= 0
              then "    (void)args;"
              else "    if (!PyArg_ParseTuple(args, \"" <> fmtStr <> "\", " <> refs <> ")) return NULL;"
      in T.unlines $
           [ "static PyObject *py_" <> cSym <> "(PyObject *self, PyObject *args) {"
           , "    (void)self;"
           ]
           ++ decls
           ++ [ parseLine
              , "    int64_t res = " <> cSym <> "(" <> callPs <> ");"
              , "    return PyLong_FromLongLong((long long)res);"
              , "}"
              ]

    renderMethodRow ex =
      let cSym   = sanitizeAbiSymbol (eaQualifiedName ex)
          pyName = formatIdentifier SnakeCase (eaQualifiedName ex)
      in "    {\"" <> pyName <> "\", py_" <> cSym <> ", METH_VARARGS, \"OrganIR FFI export\"},"

-- | Emits a Fortran 2003 @ISO_C_BINDING@ module binding every exported ABI function.
emitFortranIsoCBinding :: OrganInterface -> Text
emitFortranIsoCBinding iface =
  let modSym = T.toLower (sanitizeAbiSymbol (oiModuleName iface)) <> "_organ_ffi"
      ifaces = map renderFtnFunc (oiExports iface)
  in T.unlines $
       [ "! Generated by Frankenstein.Emit.Idiomatic — Fortran ISO_C_BINDING Module"
       , "module " <> modSym
       , "  use, intrinsic :: iso_c_binding, only: c_int64_t"
       , "  implicit none"
       , "  interface"
       ]
       ++ ifaces
       ++ [ "  end interface"
          , "end module " <> modSym
          ]
  where
    renderFtnFunc ex =
      let cSym  = sanitizeAbiSymbol (eaQualifiedName ex)
          fName = T.toLower (formatIdentifier SnakeCase (eaQualifiedName ex))
          n     = eaArity ex + eaEvParams ex
          args  = T.intercalate ", " ["a" <> T.pack (show i) | i <- [0 .. n - 1]]
          decls = ["      integer(c_int64_t), value :: a" <> T.pack (show i) | i <- [0 .. n - 1]]
      in T.unlines $
           [ "    function " <> fName <> "(" <> args <> ") result(res) bind(C, name=\"" <> cSym <> "\")"
           , "      import :: c_int64_t"
           ]
           ++ decls
           ++ [ "      integer(c_int64_t) :: res"
              , "    end function " <> fName
              ]

-- | Emits a Rocq/Iris @.v@ specification skeleton matching @.organ-iface@ contracts.
emitRocqSpecSkeleton :: OrganInterface -> Text
emitRocqSpecSkeleton iface =
  let modIdent = sanitizeAbiSymbol (oiModuleName iface)
      tags     = map renderRocqTag (oiCtors iface)
      axioms   = map renderRocqSig (oiExports iface)
  in T.unlines $
       [ "(* Generated by Frankenstein.Emit.Idiomatic — Rocq/Iris Specification Skeleton *)"
       , "From Stdlib Require Import ZArith."
       , "Module " <> modIdent <> "_Spec."
       ]
       ++ tags
       ++ axioms
       ++ [ "End " <> modIdent <> "_Spec." ]
  where
    renderRocqTag cd =
      let tName = sanitizeAbiSymbol (cdQualifiedName cd) <> "_tag"
      in "  Definition " <> tName <> " : Z := " <> T.pack (show (unContentTag (cdTag cd))) <> "%Z."

    renderRocqSig ex =
      let fName = sanitizeAbiSymbol (eaQualifiedName ex)
          n     = eaArity ex + eaEvParams ex
          ty    = T.intercalate " -> " (replicate (n + 1) "Z")
      in "  Parameter " <> fName <> " : " <> ty <> ". (* " <> T.pack (show (eaProfile ex)) <> " *)"

-- | Applies an optional external surface formatter via stdin/stdout if available on PATH.
applyFormatterHook :: Maybe FormatterHook -> Text -> IO Text
applyFormatterHook Nothing txt = pure txt
applyFormatterHook (Just hook) txt = do
  mExe <- findExecutable (T.unpack (fhCommand hook))
  case mExe of
    Nothing -> pure txt
    Just _exe -> do
      let cmd = T.unpack (fhCommand hook)
          args = map T.unpack (fhArgs hook)
      (exitCode, stdout, _stderr) <- readProcessWithExitCode cmd args (T.unpack txt)
      case exitCode of
        ExitSuccess -> pure (T.pack stdout)
        _           -> pure txt
