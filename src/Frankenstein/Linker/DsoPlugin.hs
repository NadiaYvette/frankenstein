{-# LANGUAGE DerivingStrategies #-}
{-# LANGUAGE OverloadedStrings #-}
-- | Module: Frankenstein.Linker.DsoPlugin
-- Description: Dynamic linking & DSO-as-plugin ABI verifier and C11 metadata emitter
--
-- Checks host-vs-plugin @.organ-iface@ compatibility at load or build time and
-- emits @organ_dso_meta_t@ descriptors targeting @rts/include/organ_dso.h@.
module Frankenstein.Linker.DsoPlugin
  ( DsoLayoutPolicy(..)
  , DsoManifest(..)
  , DsoCompatError(..)
  , dsoAbiVersion
  , computeInterfaceHash
  , checkDsoCompatibility
  , renderDsoMetaC11
  ) where

import qualified Data.Map.Strict as Map
import Data.Text (Text)
import qualified Data.Text as T
import Data.Word (Word32, Word64)
import Frankenstein.Core.Interface
  ( ExportAbi (..)
  , ImportReq (..)
  , MemProfile
  , OrganInterface (..)
  , fnv1a64
  )

-- | Current wire ABI version matching @ORGAN_DSO_ABI_VERSION@ in @organ_dso.h@.
dsoAbiVersion :: Word32
dsoAbiVersion = 1

-- | Layout evolution contract across the DSO seam.
data DsoLayoutPolicy
  = DsoFrozenAbi
  | DsoResilientWitness
  deriving stock (Eq, Ord, Show, Enum, Bounded)

-- | Compiled DSO plugin descriptor paired with its 'OrganInterface'.
data DsoManifest = DsoManifest
  { dmAbiVersion   :: !Word32
  , dmLayoutPolicy :: !DsoLayoutPolicy
  , dmInterface    :: !OrganInterface
  } deriving stock (Eq, Show)

-- | Load-time compatibility failure surfaced before exposing @dlsym@ pointers.
data DsoCompatError
  = AbiVersionMismatch !Word32 !Word32
  | MissingPluginSymbol !Text
  | PluginArityMismatch !Text !Int !Int
  | PluginEvidenceMismatch !Text !Int !Int
  | PluginProfileMismatch !Text !MemProfile !MemProfile
  deriving stock (Eq, Show)

-- | Deterministic 64-bit interface hash covering module name and canonical exports.
computeInterfaceHash :: OrganInterface -> Word64
computeInterfaceHash iface =
  fnv1a64 $
    T.intercalate "|" $
      oiModuleName iface
        : [ eaQualifiedName ex <> ":" <> T.pack (show (eaArity ex))
              <> ":" <> T.pack (show (eaEvParams ex))
          | ex <- oiExports iface
          ]

-- | Verifies that a dynamically loaded 'DsoManifest' satisfies a host's required 'ImportReq's.
checkDsoCompatibility :: [ImportReq] -> DsoManifest -> Either [DsoCompatError] ()
checkDsoCompatibility hostReqs dm =
  let abiErrs =
        [ AbiVersionMismatch dsoAbiVersion (dmAbiVersion dm)
        | dmAbiVersion dm /= dsoAbiVersion
        ]
      expMap = Map.fromList [(eaQualifiedName ex, ex) | ex <- oiExports (dmInterface dm)]
      reqErrs = concatMap (checkOne expMap) hostReqs
      allErrs = abiErrs ++ reqErrs
  in if null allErrs then Right () else Left allErrs
  where
    checkOne expMap req =
      let sym = irQualifiedName req
      in case Map.lookup sym expMap of
           Nothing -> [MissingPluginSymbol sym]
           Just ex ->
             [PluginArityMismatch sym (irExpectedArity req) (eaArity ex) | irExpectedArity req /= eaArity ex]
             ++ [PluginEvidenceMismatch sym (irExpectedEv req) (eaEvParams ex) | irExpectedEv req /= eaEvParams ex]
             ++ [PluginProfileMismatch sym (irMinProfile req) (eaProfile ex) | eaProfile ex < irMinProfile req]

-- | Emits the C11 @organ_dso_get_meta()@ descriptor matching @rts/include/organ_dso.h@.
renderDsoMetaC11 :: DsoManifest -> Text
renderDsoMetaC11 dm =
  let iface     = dmInterface dm
      ifaceHash = computeInterfaceHash iface
      polC      = case dmLayoutPolicy dm of
                    DsoFrozenAbi        -> "ORGAN_DSO_LAYOUT_FROZEN"
                    DsoResilientWitness -> "ORGAN_DSO_LAYOUT_RESILIENT"
      expRows   = map renderRow (oiExports iface)
      expCount  = length (oiExports iface)
  in T.unlines $
       [ "/* Generated by Frankenstein.Linker.DsoPlugin */"
       , "#include \"organ_dso.h\""
       , ""
       , "static const organ_dso_export_t g_organ_dso_exports[] = {"
       ]
       ++ (if null expRows then ["    {NULL, 0u, 0u, 0u}"] else expRows)
       ++ [ "};"
          , ""
          , "static const organ_dso_meta_t g_organ_dso_meta = {"
          , "    " <> T.pack (show (dmAbiVersion dm)) <> "u,"
          , "    " <> polC <> ","
          , "    " <> T.pack (show ifaceHash) <> "ULL,"
          , "    \"" <> oiModuleName iface <> "\","
          , "    \"" <> oiSourceLang iface <> "\","
          , "    " <> T.pack (show expCount) <> "u,"
          , "    g_organ_dso_exports"
          , "};"
          , ""
          , "ORGAN_EXPORT const organ_dso_meta_t *organ_dso_get_meta(void) {"
          , "    return &g_organ_dso_meta;"
          , "}"
          ]
  where
    renderRow ex =
      "    {\"" <> eaQualifiedName ex <> "\", "
        <> T.pack (show (eaArity ex)) <> "u, "
        <> T.pack (show (eaEvParams ex)) <> "u, "
        <> T.pack (show (fromEnum (eaProfile ex))) <> "u},"
