{-# LANGUAGE DerivingStrategies #-}
{-# LANGUAGE OverloadedStrings #-}
-- | Module: Frankenstein.Linker.PolyglotLink
-- Description: Separate-compilation polyglot linker over .organ-iface contracts
--
-- Validates heterogeneous translation units (Haskell, C, Rust) against
-- 'OrganInterface' contracts, records verified cross-language FFI edges,
-- and generates deterministic C11 extern headers for native linking.
module Frankenstein.Linker.PolyglotLink
  ( TranslationUnit(..)
  , FfiEdgeCheck(..)
  , LinkPlan(..)
  , buildPolyglotLinkPlan
  , renderExternHeaderC11
  ) where

import Data.Map.Strict (Map)
import qualified Data.Map.Strict as Map
import Data.Text (Text)
import qualified Data.Text as T
import Frankenstein.Core.Interface
  ( ExportAbi (..)
  , ImportReq (..)
  , InterfaceError
  , MemProfile
  , OrganInterface (..)
  , checkInterfaceSet
  )

-- | Separately compiled translation unit participating in a link step.
data TranslationUnit = TranslationUnit
  { tuObjectPath :: !FilePath
  , tuInterface  :: !OrganInterface
  } deriving stock (Eq, Show)

-- | Verified cross-TU boundary edge connecting an importer to its provider.
data FfiEdgeCheck = FfiEdgeCheck
  { feCallerMod  :: !Text
  , feCallerLang :: !Text
  , feCalleeMod  :: !Text
  , feCalleeLang :: !Text
  , feSymbol     :: !Text
  , feProfile    :: !MemProfile
  } deriving stock (Eq, Show)

-- | Validated separate-compilation link plan ready for native object linking.
data LinkPlan = LinkPlan
  { lpUnits      :: ![TranslationUnit]
  , lpExportMap  :: !(Map Text ExportAbi)
  , lpFfiEdges   :: ![FfiEdgeCheck]
  } deriving stock (Eq, Show)

-- | Validates all translation units via 'checkInterfaceSet' and builds the
-- cross-language FFI edge manifest.
buildPolyglotLinkPlan :: [TranslationUnit] -> Either [InterfaceError] LinkPlan
buildPolyglotLinkPlan units = do
  let ifaces = map tuInterface units
  expMap <- checkInterfaceSet ifaces
  let providerBySym =
        Map.fromList
          [ (eaQualifiedName ex, (oiModuleName iface, oiSourceLang iface))
          | iface <- ifaces
          , ex <- oiExports iface
          ]
      edges =
        [ FfiEdgeCheck
            { feCallerMod  = oiModuleName iface
            , feCallerLang = oiSourceLang iface
            , feCalleeMod  = provMod
            , feCalleeLang = provLang
            , feSymbol     = irQualifiedName req
            , feProfile    = eaProfile ex
            }
        | iface <- ifaces
        , req <- oiImports iface
        , Just ex <- [Map.lookup (irQualifiedName req) expMap]
        , Just (provMod, provLang) <- [Map.lookup (irQualifiedName req) providerBySym]
        , provMod /= oiModuleName iface
        ]
  pure LinkPlan
    { lpUnits     = units
    , lpExportMap = expMap
    , lpFfiEdges  = edges
    }

-- | Renders deterministic C11 @extern@ prototypes for all exported symbols in a 'LinkPlan'.
renderExternHeaderC11 :: LinkPlan -> Text
renderExternHeaderC11 plan =
  T.unlines $
    [ "/* Generated by Frankenstein.Linker.PolyglotLink — do not edit. */"
    , "#ifndef FRANKENSTEIN_LINK_ABI_H"
    , "#define FRANKENSTEIN_LINK_ABI_H"
    , "#include <stdint.h>"
    , ""
    ]
    ++ map renderProto (Map.elems (lpExportMap plan))
    ++ [ ""
       , "#endif /* FRANKENSTEIN_LINK_ABI_H */"
       ]
  where
    renderProto ex =
      let totalArgs = eaArity ex + eaEvParams ex
          params =
            if totalArgs <= 0
              then "void"
              else T.intercalate ", " ["int64_t a" <> T.pack (show i) | i <- [0 .. totalArgs - 1]]
      in "extern int64_t " <> sanitizeCSym (eaQualifiedName ex) <> "(" <> params <> ");"

    sanitizeCSym = T.map (\c -> if c == '.' || c == ':' || c == '-' then '_' else c)
